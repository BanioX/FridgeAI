/** Where ideas and strategy used to live. None of these may exist again. */
const MOVED = [
  ['docs', 'ideen'],
  ['docs', 'brief.md'],
  ['docs', 'blue-ocean.md'],
  ['docs', 'use-cases.md'],
].map((parts) => join(root, ...parts));

/** Generated by the SWELPER and only changed there (CLAUDE.md), or not ours to read. */
const SKIPPED_DIRS = new Set([
  '.git',
  '.claude',
  '.previews',
  '.wrangler',
  'coverage',
  'dist',
  'node_modules',
  'playwright-report',
  'test-results',
]);
const SKIPPED_FILES = new Set(['.swelper.json', 'pnpm-lock.yaml']);
const TEXT = /\.(css|html|js|json|jsonc|md|mjs|ts|tsx|txt|yaml|yml)$/;
/** Larger files are data (the product catalogue), not prose. */
const MAX_BYTES = 400_000;

function textFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((entry) => {
    const path = join(dir, entry);
    const stats = statSync(path);
    if (stats.isDirectory()) {
      return SKIPPED_DIRS.has(entry) ? [] : textFiles(path);
    }
    return TEXT.test(entry) && !SKIPPED_FILES.has(entry) && stats.size <= MAX_BYTES ? [path] : [];
  });
}

const hashes = new Map<string, string>();
function hash(word: string): string {
  const known = hashes.get(word);
  if (known !== undefined) {
    return known;
  }
  const digest = createHash('sha256').update(word).digest('hex').slice(0, 16);
  hashes.set(word, digest);
  return digest;
}

/** The words around every listed name in a text, whether written in one word or in several. */
function namesIn(text: string, names = NAMES, firstWords = FIRST_WORDS): string[] {
  const words = text.toLowerCase().match(/[a-zäöüàéèç]+/g) ?? [];
  return words.flatMap((word, index) => {
    const joined = firstWords.has(hash(word))
      ? [2, 3, 4].map((length) => words.slice(index, index + length).join(''))
      : [];
    return [word, ...joined].some((candidate) => names.has(hash(candidate)))
      ? [words.slice(index, index + 4).join(' ')]
      : [];
  });
}

describe('ideas and comparisons stay private (ADR-0065)', () => {
  it('names no other app anywhere in the repository', () => {
    const self = join(root, 'apps', 'web', 'src', 'private-ideas.test.ts');
    const found = textFiles(root)
      .filter((file) => file !== self)
      .flatMap((file) =>
        namesIn(readFileSync(file, 'utf8')).map((words) => `${relative(root, file)}: ${words}`),
      );
    expect(found).toEqual([]);
  });

  it('keeps the moved idea and strategy documents out', () => {
    expect(MOVED.filter((path) => existsSync(path))).toEqual([]);
  });

  it('finds a name written in one word or in several, in any case', () => {
    // Made-up names, so the check itself is tested without naming anyone.
    const names = new Set([hash('beispielapp'), hash('zweiworte')]);
    const firstWords = new Set([hash('zwei')]);
    expect(namesIn('Wie bei BeispielApp, nur ruhiger.', names, firstWords)).toHaveLength(1);
    expect(namesIn('Gelernt von Zwei Worte.', names, firstWords)).toHaveLength(1);
    expect(namesIn('Zwei Äpfel, drei Worte.', names, firstWords)).toEqual([]);
  });
});
