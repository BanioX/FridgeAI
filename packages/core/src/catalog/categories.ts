import { rappen } from '../money';
import type { StorageLocation } from '../model/primitives';
import type { Category, CategoryGroup, DateKind } from './category';

/**
 * Built-in category catalog (Swiss household, Migros/Coop shop).
 *
 * Sources for the shelf-life values (from knowledge, nothing fetched at build time):
 * - USDA FoodKeeper (public domain), unopened/purchase-to-expiry guidance
 * - BLV (Bundesamt fuer Lebensmittelsicherheit und Veterinaerwesen) on MHD vs. Verbrauchsdatum
 * - «Save Food, Fight Waste» / foodwaste.ch storage and leftover advice
 *
 * The values are typical estimates for an unopened pack counted from purchase, deliberately
 * conservative (rather a day too short than too long). They are NOT guarantees: the printed date
 * on the pack always wins. `null` means the location makes no sense for the category.
 *
 * use_by (Verbrauchsdatum) is used for raw meat, poultry, minced meat, sausages, sliced cold
 * cuts, fresh fish, smoked salmon and fresh ready meals. When unsure, use_by was chosen.
 */

type ShelfLife = readonly [fridge: number | null, freezer: number | null, pantry: number | null];

interface Spec {
  id: string;
  de: string;
  emoji: string;
  group: CategoryGroup;
  dateKind: DateKind;
  location: StorageLocation;
  /** Days for [fridge, freezer, pantry]. */
  shelf: ShelfLife;
  /** Price of a typical pack in Rappen; weight of a typical pack in grams. */
  price: number;
  grams?: number;
  owner: 'shared' | 'buyer';
  keywords: readonly string[];
  tips: readonly string[];
}

function def(spec: Spec): Category {
  const [fridge, freezer, pantry] = spec.shelf;
  return {
    id: spec.id,
    name: { de: spec.de },
    emoji: spec.emoji,
    group: spec.group,
    isFood: spec.group !== 'non_food',
    dateKind: spec.dateKind,
    defaultLocation: spec.location,
    shelfLifeDays: { fridge, freezer, pantry },
    avgPriceRappen: rappen(spec.price),
    ...(spec.grams === undefined ? {} : { avgWeightGrams: spec.grams }),
    defaultOwner: spec.owner,
    keywords: [...spec.keywords],
    tips: { de: [...spec.tips] },
  };
}

